# 1- logical opretors - metiqi opreatordur

# logical

   # a) and  - her iki teref dogrudursa , true qaytarir
   # b) or   - ifadelerinden biri dogrudursa , true qaytarir
   # c) not  - true olan ifadeni tersine cevirerek false, eger false olarsa true qaytarir


x = 6

print( x > 3 and x < 10 )           # true

print( x > 3 or x < 10 )            # true

print(not (x > 3 and x < 10) )      # false
